// The libdrm VCN message advertises the 1408-byte aligned length. The final
// 12 bytes are zero padding and are not part of the last IDR NAL unit.
static_assert(kDecodeH264Bitstream[PHX_VIDEO_DECODE_INPUT_BYTES - 1] == 0xf0 &&
              sizeof(kDecodeH264Bitstream) == PHX_VIDEO_DECODE_INPUT_BYTES + 12,
              "reference IDR length");
inline bool isDecodeReferenceIDR(const uint8_t *input, uint32_t bytes) {
    if (!input || bytes != PHX_VIDEO_DECODE_INPUT_BYTES) return false;
    for (uint32_t i = 0; i < bytes; ++i)
        if (input[i] != kDecodeH264Bitstream[i]) return false;
    return true;
}

